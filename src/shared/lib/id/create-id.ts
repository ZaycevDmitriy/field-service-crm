import * as Crypto from 'expo-crypto';

/**
 * Генерирует криптостойкий глобально-уникальный идентификатор (UUID v4, RFC4122).
 *
 * Фундамент идемпотентности синка (FR-09/FR-11): id новых сущностей (фото, будущие
 * мутации) назначается на клиенте и должен быть глобально уникален и невоспроизводим —
 * иначе повторная отправка мутации после обрыва связи создаст дубль на сервере.
 */
export function createId(): string {
  return Crypto.randomUUID();
}
